// ── Contract discovery ────────────────────────────────────────────────────

interface ContractCrate {
  /** Cargo package name, e.g. `linkora-vesting`. */
  crate: string;
  /** Generated module file stem, e.g. `vesting`. */
  module: string;
  /** Namespace the barrel exports the module under, e.g. `vesting`. */
  namespace: string;
  /** PascalCase prefix for the operation builder class, e.g. `Vesting`. */
  pascal: string;
  wasmFile: string;
}

/** Every workspace member built as a contract (`crate-type` includes `cdylib`). */
function discoverContracts(): ContractCrate[] {
  const workspace = readFileSync(resolve(CONTRACTS_DIR, "Cargo.toml"), "utf-8");
  const members = [
    ...(workspace.match(/members\s*=\s*\[([\s\S]*?)\]/)?.[1] ?? "").matchAll(/"([^"]+)"/g),
  ]
    .map((m) => m[1]!)
    .sort();
  const crates: ContractCrate[] = [];
  for (const member of members) {
    const manifest = readFileSync(resolve(CONTRACTS_DIR, member, "Cargo.toml"), "utf-8");
    if (!/crate-type\s*=\s*\[[^\]]*"cdylib"/.test(manifest)) continue;
    const crate = manifest.match(/^name\s*=\s*"([^"]+)"/m)?.[1];
    if (!crate) throw new Error(`No package name in ${member}/Cargo.toml`);
    const module = crate === "linkora-contracts" ? "linkora" : crate.replace(/^linkora-/, "");
    crates.push({
      crate,
      module,
      namespace: camel(module.replace(/-/g, "_")),
      pascal: pascal(module.replace(/-/g, "_")),
      wasmFile: `${crate.replace(/-/g, "_")}.wasm`,
    });
  }
  return crates;
}

function readSpec(wasmDir: string, c: ContractCrate): { entries: xdr.ScSpecEntry[]; hash: string } {
  const path = resolve(wasmDir, c.wasmFile);
  if (!existsSync(path)) {
    throw new Error(
      `WASM for ${c.crate} not found at ${relative(ROOT, path)} — run 'pnpm build:contracts' first.`
    );
  }
  const entries = contract.Spec.fromWasm(readFileSync(path)).entries;
  const hash = createHash("sha256")
    .update(Buffer.concat(entries.map((e) => e.toXDR())))
    .digest("hex");
  return { entries, hash };
}

// ── Naming ────────────────────────────────────────────────────────────────

function pascal(s: string): string {
  return s
    .split(/_+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function camel(s: string): string {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

function constCase(s: string): string {
  return s
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toUpperCase();
}

const str = (v: string | Buffer) => v.toString();

function jsdoc(doc: string | Buffer, indent = ""): string[] {
  const text = str(doc).trim().replace(/\*\//g, "*\\/");
  if (!text) return [];
  return [
    `${indent}/**`,
    ...text.split("\n").map((l) => `${indent} * ${l}`.trimEnd()),
    `${indent} */`,
  ];
}

// ── Per-module generator ──────────────────────────────────────────────────

type Udt =
  | { kind: "struct"; def: xdr.ScSpecUdtStructV0 }
  | { kind: "union"; def: xdr.ScSpecUdtUnionV0 }
  | { kind: "enum"; def: xdr.ScSpecUdtEnumV0 }
  | { kind: "error"; def: xdr.ScSpecUdtErrorEnumV0 };

const isTupleStruct = (s: xdr.ScSpecUdtStructV0) =>
  s.fields().length > 0 && s.fields().every((f, i) => str(f.name()) === String(i));

class ModuleGen {
  private readonly udts = new Map<string, Udt>();
  private tmp = 0;

  constructor(
    private readonly c: ContractCrate,
    private readonly entries: xdr.ScSpecEntry[],
    private readonly hash: string
  ) {
    for (const e of entries) {
      switch (e.switch().name) {
        case "scSpecEntryUdtStructV0":
          this.addUdt({ kind: "struct", def: e.udtStructV0() });
          break;
        case "scSpecEntryUdtUnionV0":
          this.addUdt({ kind: "union", def: e.udtUnionV0() });
          break;
        case "scSpecEntryUdtEnumV0":
          this.addUdt({ kind: "enum", def: e.udtEnumV0() });
          break;
        case "scSpecEntryUdtErrorEnumV0":
          this.addUdt({ kind: "error", def: e.udtErrorEnumV0() });
          break;
      }
    }
  }

  private addUdt(u: Udt) {
    this.udts.set(str(u.def.name()), u);
  }

  private v(): string {
    return `v${this.tmp++}`;
  }

  // ── Type mapping ──────────────────────────────────────────────────────

  tsType(t: xdr.ScSpecTypeDef): string {
    switch (t.switch().name) {
      case "scSpecTypeVal":
        return "xdr.ScVal";
      case "scSpecTypeBool":
        return "boolean";
      case "scSpecTypeVoid":
        return "void";
      case "scSpecTypeError":
        return "number";
      case "scSpecTypeU32":
      case "scSpecTypeI32":
        return "number";
      case "scSpecTypeU64":
      case "scSpecTypeI64":
      case "scSpecTypeTimepoint":
      case "scSpecTypeDuration":
      case "scSpecTypeU128":
      case "scSpecTypeI128":
      case "scSpecTypeU256":
      case "scSpecTypeI256":
        return "bigint";
      case "scSpecTypeBytes":
      case "scSpecTypeBytesN":
        return "Uint8Array";
      case "scSpecTypeString":
      case "scSpecTypeSymbol":
      case "scSpecTypeAddress":
      case "scSpecTypeMuxedAddress":
        return "string";
      case "scSpecTypeOption":
        return `${this.tsType(t.option().valueType())} | null`;
      case "scSpecTypeResult":
        return this.tsType(t.result().okType());
      case "scSpecTypeVec":
        return `Array<${this.tsType(t.vec().elementType())}>`;
      case "scSpecTypeMap":
        return `Map<${this.tsType(t.map().keyType())}, ${this.tsType(t.map().valueType())}>`;
      case "scSpecTypeTuple":
        return `[${t
          .tuple()
          .valueTypes()
          .map((x) => this.tsType(x))
          .join(", ")}]`;
      case "scSpecTypeUdt":
        return this.udtName(t);
      default:
        throw new Error(`Unsupported spec type ${t.switch().name}`);
    }
  }

  private udtName(t: xdr.ScSpecTypeDef): string {
    const name = str(t.udt().name());
    if (!this.udts.has(name)) throw new Error(`${this.c.crate}: unknown type ${name}`);
    return name;
  }

  /** TS expression encoding `e` (of spec type `t`) as an `xdr.ScVal`. */
  enc(t: xdr.ScSpecTypeDef, e: string): string {
    switch (t.switch().name) {
      case "scSpecTypeVal":
        return e;
      case "scSpecTypeBool":
        return `rt.encodeBool(${e})`;
      case "scSpecTypeVoid":
        return "rt.encodeVoid()";
      case "scSpecTypeError":
        return `rt.encodeContractError(${e})`;
      case "scSpecTypeU32":
        return `rt.encodeU32(${e})`;
      case "scSpecTypeI32":
        return `rt.encodeI32(${e})`;
      case "scSpecTypeU64":
        return `rt.encodeU64(${e})`;
      case "scSpecTypeI64":
        return `rt.encodeI64(${e})`;
      case "scSpecTypeTimepoint":
        return `rt.encodeTimepoint(${e})`;
      case "scSpecTypeDuration":
        return `rt.encodeDuration(${e})`;
      case "scSpecTypeU128":
        return `rt.encodeU128(${e})`;
      case "scSpecTypeI128":
        return `rt.encodeI128(${e})`;
      case "scSpecTypeU256":
        return `rt.encodeU256(${e})`;
      case "scSpecTypeI256":
        return `rt.encodeI256(${e})`;
      case "scSpecTypeBytes":
        return `rt.encodeBytes(${e})`;
      case "scSpecTypeBytesN":
        return `rt.encodeBytesN(${e}, ${t.bytesN().n()})`;
      case "scSpecTypeString":
        return `rt.encodeString(${e})`;
      case "scSpecTypeSymbol":
        return `rt.encodeSymbol(${e})`;
      case "scSpecTypeAddress":
      case "scSpecTypeMuxedAddress":
        return `rt.encodeAddress(${e})`;
      case "scSpecTypeOption": {
        const x = this.v();
        return `rt.encodeOption(${e}, (${x}) => ${this.enc(t.option().valueType(), x)})`;
      }
      case "scSpecTypeResult":
        return this.enc(t.result().okType(), e);
      case "scSpecTypeVec": {
        const x = this.v();
        return `rt.encodeVec(${e}, (${x}) => ${this.enc(t.vec().elementType(), x)})`;
      }
      case "scSpecTypeMap": {
        const k = this.v();
        const val = this.v();
        return `rt.encodeMap(${e}, (${k}) => ${this.enc(t.map().keyType(), k)}, (${val}) => ${this.enc(
          t.map().valueType(),
          val
        )})`;
      }
      case "scSpecTypeTuple":
        return `rt.encodeTuple([${t
          .tuple()
          .valueTypes()
          .map((vt, i) => this.enc(vt, `${e}[${i}]`))
          .join(", ")}])`;
      case "scSpecTypeUdt":
        return `encode${this.udtName(t)}(${e})`;
      default:
        throw new Error(`Unsupported spec type ${t.switch().name}`);
    }
  }

  /** TS expression decoding the `xdr.ScVal` `e` into spec type `t`. */
  dec(t: xdr.ScSpecTypeDef, e: string): string {
    switch (t.switch().name) {
      case "scSpecTypeVal":
        return e;
      case "scSpecTypeBool":
        return `rt.decodeBool(${e})`;
      case "scSpecTypeVoid":
        return `rt.decodeVoid(${e})`;
      case "scSpecTypeError":
        return `rt.decodeContractError(${e})`;
      case "scSpecTypeU32":
        return `rt.decodeU32(${e})`;
      case "scSpecTypeI32":
        return `rt.decodeI32(${e})`;
      case "scSpecTypeU64":
        return `rt.decodeU64(${e})`;
      case "scSpecTypeI64":
        return `rt.decodeI64(${e})`;
      case "scSpecTypeTimepoint":
        return `rt.decodeTimepoint(${e})`;
      case "scSpecTypeDuration":
        return `rt.decodeDuration(${e})`;
      case "scSpecTypeU128":
        return `rt.decodeU128(${e})`;
      case "scSpecTypeI128":
        return `rt.decodeI128(${e})`;
      case "scSpecTypeU256":
        return `rt.decodeU256(${e})`;
      case "scSpecTypeI256":
        return `rt.decodeI256(${e})`;
      case "scSpecTypeBytes":
        return `rt.decodeBytes(${e})`;
      case "scSpecTypeBytesN":
        return `rt.decodeBytesN(${e}, ${t.bytesN().n()})`;
      case "scSpecTypeString":
        return `rt.decodeString(${e})`;
      case "scSpecTypeSymbol":
        return `rt.decodeSymbol(${e})`;
      case "scSpecTypeAddress":
      case "scSpecTypeMuxedAddress":
        return `rt.decodeAddress(${e})`;
      case "scSpecTypeOption": {
        const x = this.v();
        return `rt.decodeOption(${e}, (${x}) => ${this.dec(t.option().valueType(), x)})`;
      }
      case "scSpecTypeResult":
        return this.dec(t.result().okType(), e);
      case "scSpecTypeVec": {
        const x = this.v();
        return `rt.decodeVec(${e}, (${x}) => ${this.dec(t.vec().elementType(), x)})`;
      }
      case "scSpecTypeMap": {
        const k = this.v();
        const val = this.v();
        return `rt.decodeMap(${e}, (${k}) => ${this.dec(t.map().keyType(), k)}, (${val}) => ${this.dec(
          t.map().valueType(),
          val
        )})`;
      }
      case "scSpecTypeTuple": {
        const types = t.tuple().valueTypes();
        const items = this.v();
        return `((${items}: xdr.ScVal[]): ${this.tsType(t)} => [${types
          .map((vt, i) => this.dec(vt, `rt.item(${items}, ${i})`))
          .join(", ")}])(rt.decodeTuple(${e}, ${types.length}))`;
      }
      case "scSpecTypeUdt":
        return `decode${this.udtName(t)}(${e})`;
      default:
        throw new Error(`Unsupported spec type ${t.switch().name}`);
    }
  }

  // ── Emitters ──────────────────────────────────────────────────────────

  private emitStruct(s: xdr.ScSpecUdtStructV0): string[] {
    const name = str(s.name());
    const fields = s.fields();
    const out = [...jsdoc(s.doc())];
    if (isTupleStruct(s)) {
      out.push(
        `export type ${name} = [${fields.map((f) => this.tsType(f.type())).join(", ")}];`,
        ""
      );
      out.push(
        `export function encode${name}(v: ${name}): xdr.ScVal {`,
        `  return rt.encodeTuple([${fields.map((f, i) => this.enc(f.type(), `v[${i}]`)).join(", ")}]);`,
        "}",
        "",
        `export function decode${name}(v: xdr.ScVal): ${name} {`,
        `  const items = rt.decodeTuple(v, ${fields.length});`,
        `  return [${fields.map((f, i) => this.dec(f.type(), `rt.item(items, ${i})`)).join(", ")}];`,
        "}",
        ""
      );
      return out;
    }
    out.push(`export interface ${name} {`);
    for (const f of fields) {
      out.push(...jsdoc(f.doc(), "  "), `  ${str(f.name())}: ${this.tsType(f.type())};`);
    }
    out.push("}", "");
    out.push(
      `export function encode${name}(v: ${name}): xdr.ScVal {`,
      "  return rt.encodeStruct([",
      ...fields.map(
        (f) => `    ["${str(f.name())}", ${this.enc(f.type(), `v.${str(f.name())}`)}],`
      ),
      "  ]);",
      "}",
      "",
      `export function decode${name}(v: xdr.ScVal): ${name} {`,
      `  const f = rt.decodeStruct(v, "${name}");`,
      "  return {",
      ...fields.map(
        (f) => `    ${str(f.name())}: ${this.dec(f.type(), `rt.field(f, "${str(f.name())}")`)},`
      ),
      "  };",
      "}",
      ""
    );
    return out;
  }

  private emitUnion(u: xdr.ScSpecUdtUnionV0): string[] {
    const name = str(u.name());
    const cases = u.cases().map((c) =>
      c.switch().name === "scSpecUdtUnionCaseVoidV0"
        ? {
            name: str(c.voidCase().name()),
            doc: c.voidCase().doc(),
            types: [] as xdr.ScSpecTypeDef[],
          }
        : {
            name: str(c.tupleCase().name()),
            doc: c.tupleCase().doc(),
            types: c.tupleCase().type(),
          }
    );
    const out = [...jsdoc(u.doc())];
    if (cases.every((c) => c.types.length === 0)) {
      const tags = cases.map((c) => `"${c.name}"`);
      out.push(
        `export type ${name} = ${tags.join(" | ")};`,
        "",
        `export const ${constCase(name)}_VALUES: readonly ${name}[] = [${tags.join(", ")}];`,
        "",
        `export function encode${name}(v: ${name}): xdr.ScVal {`,
        "  return rt.encodeUnionCase(v, []);",
        "}",
        "",
        `export function decode${name}(v: xdr.ScVal): ${name} {`,
        `  return rt.decodeUnitUnion(v, ${constCase(name)}_VALUES, "${name}");`,
        "}",
        ""
      );
      return out;
    }
    out.push(`export type ${name} =`);
    for (const c of cases) {
      const values = c.types.length
        ? `; values: [${c.types.map((t) => this.tsType(t)).join(", ")}]`
        : "";
      out.push(`  | { tag: "${c.name}"${values} }`);
    }
    out.push(";", "");
    out.push(`export function encode${name}(v: ${name}): xdr.ScVal {`, "  switch (v.tag) {");
    for (const c of cases) {
      out.push(
        `    case "${c.name}":`,
        `      return rt.encodeUnionCase("${c.name}", [${c.types
          .map((t, i) => this.enc(t, `v.values[${i}]`))
          .join(", ")}]);`
      );
    }
    out.push("  }", "}", "");
    out.push(
      `export function decode${name}(v: xdr.ScVal): ${name} {`,
      `  const [tag, values] = rt.decodeUnionCase(v, "${name}");`,
      "  switch (tag) {"
    );
    for (const c of cases) {
      const vals = c.types.length
        ? `, values: [${c.types.map((t, i) => this.dec(t, `rt.item(values, ${i})`)).join(", ")}]`
        : "";
      out.push(`    case "${c.name}":`, `      return { tag: "${c.name}"${vals} };`);
    }
    out.push(
      "    default:",
      `      throw new rt.DecodeError(\`Unknown ${name} case \${tag}\`);`,
      "  }",
      "}",
      ""
    );
    return out;
  }

  private emitIntEnum(
    e: xdr.ScSpecUdtEnumV0 | xdr.ScSpecUdtErrorEnumV0,
    isError: boolean
  ): string[] {
    const name = str(e.name());
    const cases = e.cases().map((c) => ({ name: str(c.name()), value: c.value(), doc: c.doc() }));
    const out = [...jsdoc(e.doc()), `export enum ${name} {`];
    for (const c of cases) out.push(...jsdoc(c.doc, "  "), `  ${c.name} = ${c.value},`);
    out.push("}", "");
    const values = `[${cases.map((c) => c.value).join(", ")}]`;
    if (isError) {
      out.push(
        `/** Human-readable name of a \`${name}\` contract error code. */`,
        `export function ${camel(name)}Name(code: number): string | undefined {`,
        `  return ${name}[code];`,
        "}",
        "",
        `export function encode${name}(v: ${name}): xdr.ScVal {`,
        "  return rt.encodeContractError(v);",
        "}",
        "",
        `export function decode${name}(v: xdr.ScVal): ${name} {`,
        `  return rt.decodeIntEnum(rt.decodeContractError(v), ${values}, "${name}") as ${name};`,
        "}",
        ""
      );
    } else {
      out.push(
        `export function encode${name}(v: ${name}): xdr.ScVal {`,
        "  return rt.encodeU32(v);",
        "}",
        "",
        `export function decode${name}(v: xdr.ScVal): ${name} {`,
        `  return rt.decodeIntEnum(rt.decodeU32(v), ${values}, "${name}") as ${name};`,
        "}",
        ""
      );
    }
    return out;
  }

  private functions(): xdr.ScSpecFunctionV0[] {
    return this.entries
      .filter((e) => e.switch().name === "scSpecEntryFunctionV0")
      .map((e) => e.functionV0())
      .filter((f) => !str(f.name()).startsWith("__"));
  }

  private events(): xdr.ScSpecEventV0[] {
    return this.entries
      .filter((e) => e.switch().name === "scSpecEntryEventV0")
      .map((e) => e.eventV0());
  }

  private emitFunctions(): string[] {
    const out: string[] = [
      "// ── Functions ──────────────────────────────────────────────────────────",
      "",
    ];
    const fns = this.functions();
    for (const f of fns) {
      const name = str(f.name());
      const P = pascal(name);
      const inputs = f.inputs();
      const ret = f.outputs()[0];
      const argsType = inputs.length ? `${P}Args` : "rt.NoArgs";
      if (inputs.length) {
        out.push(...jsdoc(f.doc()), `export interface ${P}Args {`);
        for (const i of inputs) {
          out.push(...jsdoc(i.doc(), "  "), `  ${str(i.name())}: ${this.tsType(i.type())};`);
        }
        out.push("}", "");
      }
      out.push(
        `/** Arguments of \`${name}\`, in call order. */`,
        `export function encode${P}Args(${inputs.length ? "args" : "_args"}: ${argsType}${
          inputs.length ? "" : " = {}"
        }): xdr.ScVal[] {`,
        `  return [${inputs.map((i) => this.enc(i.type(), `args.${str(i.name())}`)).join(", ")}];`,
        "}",
        "",
        `/** Return value of \`${name}\`. */`,
        `export function decode${P}Result(v: xdr.ScVal): ${ret ? this.tsType(ret) : "void"} {`,
        ret ? `  return ${this.dec(ret, "v")};` : "  rt.decodeVoid(v);",
        "}",
        ""
      );
    }

    out.push(
      "/** Every contract function: its name, argument encoder and result decoder. */",
      "export const methods = {"
    );
    for (const f of fns) {
      const name = str(f.name());
      const P = pascal(name);
      out.push(
        `  ${name}: { name: "${name}", encodeArgs: encode${P}Args, decodeResult: decode${P}Result },`
      );
    }
    out.push("} as const;", "", "export type MethodName = keyof typeof methods;", "");

    out.push(
      `/**`,
      ` * Builds \`invokeHostFunction\` operations for the ${this.c.crate} contract.`,
      ` * Add one to a transaction, simulate it, sign and submit as usual.`,
      ` */`,
      `export class ${this.c.pascal}Contract {`,
      "  constructor(public readonly contractId: string) {}",
      ""
    );
    for (const f of fns) {
      const name = str(f.name());
      const P = pascal(name);
      const hasArgs = f.inputs().length > 0;
      out.push(
        ...jsdoc(f.doc(), "  "),
        `  ${camel(name)}(${hasArgs ? `args: ${P}Args` : ""}): xdr.Operation {`,
        `    return rt.invoke(this.contractId, "${name}", encode${P}Args(${hasArgs ? "args" : ""}));`,
        "  }",
        ""
      );
    }
    out.push("}", "");
    return out;
  }

  private emitEvents(): string[] {
    const events = this.events();
    if (events.length === 0) return [];
    const out: string[] = [
      "// ── Events ─────────────────────────────────────────────────────────────",
      "",
    ];
    for (const ev of events) {
      const name = str(ev.name());
      const prefix = ev.prefixTopics().map(str);
      const params = ev.params();
      const topicParams = params.filter(
        (p) => p.location().name === "scSpecEventParamLocationTopicList"
      );
      const dataParams = params.filter((p) => p.location().name === "scSpecEventParamLocationData");
      const format = ev.dataFormat().name;

      out.push(...jsdoc(ev.doc()), `export interface ${name} {`);
      for (const p of params)
        out.push(...jsdoc(p.doc(), "  "), `  ${str(p.name())}: ${this.tsType(p.type())};`);
      out.push("}", "");
      out.push(
        `/** Leading topic(s) identifying \`${name}\`. */`,
        `export const ${constCase(name)}_TOPICS = [${prefix.map((p) => `"${p}"`).join(", ")}] as const;`,
        "",
        `export function decode${name}(topics: xdr.ScVal[], data: xdr.ScVal): ${name} {`,
        `  rt.expectTopics(topics, ${constCase(name)}_TOPICS, ${topicParams.length}, "${name}");`
      );
      let dataExpr: (i: number, field: string) => string;
      if (dataParams.length === 0) {
        dataExpr = () => "";
      } else if (format === "scSpecEventDataFormatMap") {
        out.push(`  const d = rt.decodeStruct(data, "${name}");`);
        dataExpr = (_i, field) => `rt.field(d, "${field}")`;
      } else if (format === "scSpecEventDataFormatVec") {
        out.push(`  const d = rt.decodeTuple(data, ${dataParams.length});`);
        dataExpr = (i) => `rt.item(d, ${i})`;
      } else {
        dataExpr = () => "data";
      }
      out.push("  return {");
      for (const p of params) {
        const field = str(p.name());
        const ti = topicParams.indexOf(p);
        const src =
          ti >= 0
            ? `rt.item(topics, ${prefix.length + ti})`
            : dataExpr(dataParams.indexOf(p), field);
        out.push(`    ${field}: ${this.dec(p.type(), src)},`);
      }
      out.push("  };", "}", "");
    }

    out.push(
      "/** Any event this contract emits, tagged by its spec name. */",
      "export type ContractEvent ="
    );
    for (const ev of events)
      out.push(`  | { name: "${str(ev.name())}"; event: ${str(ev.name())} }`);
    out.push(";", "");
    out.push(
      "/**",
      " * Decode a contract event from its topics and data, or return `null` when",
      " * the topics do not belong to an event of this contract.",
      " */",
      "export function decodeEvent(topics: xdr.ScVal[], data: xdr.ScVal): ContractEvent | null {",
      "  const first = topics[0];",
      "  if (!first || first.switch() !== xdr.ScValType.scvSymbol()) return null;",
      "  switch (first.sym().toString()) {"
    );
    for (const ev of events) {
      const name = str(ev.name());
      const topic = ev.prefixTopics().map(str)[0];
      out.push(
        `    case "${topic}":`,
        `      return { name: "${name}", event: decode${name}(topics, data) };`
      );
    }
    out.push("    default:", "      return null;", "  }", "}", "");
    return out;
  }

  emit(): string {
    const out: string[] = [
      ...HEADER,
      `// Source: ${this.c.crate} (packages/contracts, ${this.c.wasmFile}).`,
      "",
      'import { xdr } from "@stellar/stellar-base";',
      'import * as rt from "./runtime.js";',
      "",
      `/** sha256 of the contract spec these bindings were generated from. */`,
      `export const SPEC_HASH = "${this.hash}";`,
      "",
      "// ── Types ──────────────────────────────────────────────────────────────",
      "",
    ];
    for (const [, u] of [...this.udts].sort(([a], [b]) => a.localeCompare(b))) {
      if (u.kind === "struct") out.push(...this.emitStruct(u.def));
      else if (u.kind === "union") out.push(...this.emitUnion(u.def));
      else out.push(...this.emitIntEnum(u.def, u.kind === "error"));
    }
    out.push(...this.emitFunctions(), ...this.emitEvents());
    return out.join("\n");
  }
}

