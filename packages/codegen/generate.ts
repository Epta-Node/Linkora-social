/**
 * Contract ABI → TypeScript codegen (Epta-Node#1769).
 *
 * For every contract crate in the `packages/contracts` workspace this script
 * reads the compiled `.wasm`, extracts the contract spec (the
 * `contractspecv0` custom section, decoded as `xdr.ScSpecEntry` values) and
 * emits `packages/sdk/src/generated/contracts/<module>.ts` with:
 *
 * - TypeScript types for every struct, union, enum, error enum and event;
 * - `xdr.ScVal` encoders / decoders for each of those types;
 * - for each contract function, an `Args` interface, an argument encoder and
 *   a result decoder, plus a typed `<Name>Contract` operation builder.
 *
 * No `stellar` CLI is needed: the spec is read straight from the WASM.
 *
 * Usage:
 *   pnpm codegen         # build the contracts, then regenerate
 *   pnpm codegen:check   # build, regenerate in memory, fail if files are stale
 *
 * `tsx generate.ts [--check] [--wasm-dir <dir>]`
 */
