/** Soroban map keys must be sorted the way the host orders ScVals. */
function compareScVal(a: xdr.ScVal, b: xdr.ScVal): number {
  if (a.switch() !== b.switch()) return a.switch().value - b.switch().value;
  switch (a.switch()) {
    case xdr.ScValType.scvU32():
    case xdr.ScValType.scvI32():
    case xdr.ScValType.scvU64():
    case xdr.ScValType.scvI64():
    case xdr.ScValType.scvU128():
    case xdr.ScValType.scvI128():
    case xdr.ScValType.scvU256():
    case xdr.ScValType.scvI256(): {
      const x = scValToBigInt(a);
      const y = scValToBigInt(b);
      return x < y ? -1 : x > y ? 1 : 0;
    }
    case xdr.ScValType.scvSymbol():
      return Buffer.compare(Buffer.from(a.sym()), Buffer.from(b.sym()));
    case xdr.ScValType.scvString():
      return Buffer.compare(Buffer.from(a.str()), Buffer.from(b.str()));
    case xdr.ScValType.scvBytes():
      return Buffer.compare(a.bytes(), b.bytes());
    default:
      return Buffer.compare(a.toXDR(), b.toXDR());
  }
}

export function encodeMap<K, V>(
  v: ReadonlyMap<K, V>,
  encKey: (k: K) => xdr.ScVal,
  encVal: (x: V) => xdr.ScVal
): xdr.ScVal {
  const entries = [...v].map(
    ([k, x]) => new xdr.ScMapEntry({ key: encKey(k), val: encVal(x) })
  );
  entries.sort((a, b) => compareScVal(a.key(), b.key()));
  return xdr.ScVal.scvMap(entries);
}
export function decodeMap<K, V>(
  v: xdr.ScVal,
  decKey: (k: xdr.ScVal) => K,
  decVal: (x: xdr.ScVal) => V
): Map<K, V> {
  expectType(v, xdr.ScValType.scvMap(), "map");
  return new Map((v.map() ?? []).map((e) => [decKey(e.key()), decVal(e.val())]));
}

