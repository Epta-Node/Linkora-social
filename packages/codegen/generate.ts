function parseArgs(argv: string[]): { check: boolean; wasmDir: string } {
  let check = false;
  let wasmDir = resolve(CONTRACTS_DIR, "target/wasm32v1-none/release");
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") check = true;
    else if (argv[i] === "--wasm-dir") wasmDir = resolve(argv[++i] ?? "");
    else throw new Error(`Unknown argument ${argv[i]}`);
  }
  return { check, wasmDir };
}

async function format(path: string, source: string): Promise<string> {
  const options = (await prettier.resolveConfig(path)) ?? {};
  return prettier.format(source, { ...options, filepath: path });
}

async function main() {
  const { check, wasmDir } = parseArgs(process.argv.slice(2));
  const crates = discoverContracts();
  const files = new Map<string, string>();
  const hashes: string[] = [];

  for (const c of crates) {
    const { entries, hash } = readSpec(wasmDir, c);
    files.set(resolve(OUT_DIR, `${c.module}.ts`), new ModuleGen(c, entries, hash).emit());
    hashes.push(`${hash}  ${c.crate}`);
    console.log(`  ${c.crate}: ${entries.length} spec entries (${hash.slice(0, 12)})`);
  }

  files.set(resolve(OUT_DIR, "runtime.ts"), [...HEADER, RUNTIME].join("\n"));
  files.set(
    resolve(OUT_DIR, "index.ts"),
    [
      ...HEADER,
      "/**",
      " * Spec-derived bindings for every Linkora contract, one namespace each.",
      " * Side-effect free, so bundlers drop the contracts an app does not use.",
      " */",
      "",
      ...crates.map((c) => `export * as ${c.namespace} from "./${c.module}.js";`),
      'export { DecodeError } from "./runtime.js";',
      "",
    ].join("\n")
  );

  const outputs = new Map<string, string>();
  for (const [path, source] of files) outputs.set(path, await format(path, source));
  outputs.set(HASH_FILE, hashes.join("\n") + "\n");

  const existing = existsSync(OUT_DIR) ? readdirSync(OUT_DIR).map((f) => resolve(OUT_DIR, f)) : [];
  const extra = existing.filter((p) => !outputs.has(p));

  if (check) {
    const stale = [...outputs].filter(
      ([path, content]) => !existsSync(path) || readFileSync(path, "utf-8") !== content
    );
    for (const [path] of stale) console.error(`  stale: ${relative(ROOT, path)}`);
    for (const path of extra) console.error(`  unexpected: ${relative(ROOT, path)}`);
    if (stale.length || extra.length) {
      console.error(
        "\nGenerated contract bindings are out of date — run `pnpm codegen` and commit."
      );
      process.exit(1);
    }
    console.log("\n✅ Generated contract bindings are up to date.");
    return;
  }

  mkdirSync(OUT_DIR, { recursive: true });
  for (const path of extra) rmSync(path);
  for (const [path, content] of outputs) {
    writeFileSync(path, content);
    console.log(`  ✓ ${relative(ROOT, path)}`);
  }
  console.log(`\n✅ Codegen complete (${crates.map((c) => basename(c.module)).join(", ")}).`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
